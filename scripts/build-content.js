#!/usr/bin/env node
/*
 * Regenerates content.js (the offline file:/// fallback) from data/*.json.
 * data/*.json is the source of truth; never edit content.js by hand.
 *
 *   node scripts/build-content.js          write content.js
 *   node scripts/build-content.js --check  exit 1 if content.js is stale
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'data', `${name}.json`), 'utf8'));
const json = value => JSON.stringify(value, null, 2);

const records = {
  experience: read('experience'),
  projects: read('projects'),
  certificates: read('certifications'),
  research: read('research')
};

const output = `/* GENERATED by scripts/build-content.js from data/*.json. Do not edit by hand. */
window.PORTFOLIO_CONFIG = Object.freeze(${json(read('profile'))});

window.PORTFOLIO_RECORDS = ${json(records)};

window.PORTFOLIO_I18N = ${json(read('i18n'))};
`;

const target = path.join(root, 'content.js');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== output) {
    console.error('content.js is out of date. Run: node scripts/build-content.js');
    process.exit(1);
  }
  console.log('content.js is up to date.');
} else {
  fs.writeFileSync(target, output);
  console.log('content.js regenerated from data/*.json');
}
